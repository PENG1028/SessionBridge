#!/usr/bin/env node
// ─── generate-plugin-registry.mjs ──────────────────────────────────
// Scans plugins/*/plugin.yaml and auto-generates plugins/registry.ts.
// Run before `next dev` or `next build` — no manual registry edits.
//
// Convention (per plugin.yaml):
//   adapters.system-ui.views:
//     - entry: ./index          → default export
//     - entry: ./index#FooBar   → named export "FooBar"

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pluginsDir = join(__dirname, '..', 'plugins');
const registryPath = join(pluginsDir, 'registry.ts');

const entries = [];

for (const name of readdirSync(pluginsDir, { withFileTypes: true })) {
  if (!name.isDirectory()) continue;
  const yamlPath = join(pluginsDir, name.name, 'plugin.yaml');
  let manifest;
  try {
    manifest = yaml.load(readFileSync(yamlPath, 'utf8'));
  } catch {
    console.warn(`[registry] skipping ${name.name}: cannot read plugin.yaml`);
    continue;
  }

  const views = manifest?.adapters?.['system-ui']?.views;
  if (!views || views.length === 0) continue;

  for (const view of views) {
    if (view.type !== 'custom-react' || !view.entry) continue;

    const viewId = view.id || manifest.id;
    let entryPath = view.entry;        // e.g. "./index" or "./index#ExportName"
    let exportName = 'default';

    const hashIdx = entryPath.lastIndexOf('#');
    if (hashIdx >= 0) {
      exportName = entryPath.slice(hashIdx + 1);
      entryPath = entryPath.slice(0, hashIdx);
    }

    // Resolve to a path relative to plugins/registry.ts
    const resolved = './' + relative(pluginsDir, join(pluginsDir, name.name, entryPath)).replace(/\\/g, '/');

    entries.push({
      viewId,
      resolved,
      exportName,
      pluginDir: name.name,
    });
  }
}

// ── Generate registry.ts ──────────────────────────────────────────
const lines = [
  `'use client';`,
  ``,
  `// Auto-generated by scripts/generate-plugin-registry.mjs — DO NOT EDIT.`,
  `// Scans plugins/*/plugin.yaml for custom-react views and builds`,
  `// the dynamic import map. Re-run this script after adding/removing plugins.`,
  ``,
  `import type { ComponentType } from 'react';`,
  `import type { HostComponentProps } from '../sdk';`,
  ``,
  `export const pluginComponents: Record<`,
  `  string,`,
  `  () => Promise<{ default: ComponentType<any> }>`,
  `> = {`,
];

for (const e of entries) {
  if (e.exportName === 'default') {
    lines.push(`  '${e.viewId}': () => import('${e.resolved}'),`);
  } else {
    lines.push(`  '${e.viewId}': () => import('${e.resolved}').then(m => ({ default: m.${e.exportName} as ComponentType<HostComponentProps> })),`);
  }
}

lines.push('};');
lines.push('');

writeFileSync(registryPath, lines.join('\n'), 'utf8');
console.log(`[registry] wrote ${entries.length} plugin component(s) to plugins/registry.ts`);
for (const e of entries) {
  console.log(`  ${e.pluginDir}/${e.viewId} → ${e.resolved}${e.exportName !== 'default' ? '#' + e.exportName : ''}`);
}
